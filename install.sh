#!/bin/bash
# Prefixa IPv6 Gateway v7.6 installer
# One-liner:
#   curl -fsSL https://raw.githubusercontent.com/jeffpecky/ipv6-proxy/main/install.sh | sudo bash
#
# The proxy itself is built with `go install` from the repo (index.html is embedded in the binary).

# --- Hurricane Electric 6in4 tunnel (required) ------------------------------
# The gateway is useless without a routable prefix, and a VPS with no native
# IPv6 reaches one through an HE tunnel. Values come from install.env.
HE_TUNNEL_ID="${HE_TUNNEL_ID:-}"
HE_SERVER_V4="${HE_SERVER_V4:-}"
HE_SERVER_V6="${HE_SERVER_V6:-}"
HE_CLIENT_V6="${HE_CLIENT_V6:-}"
HE_ENDPOINT_V4="${HE_ENDPOINT_V4:-}"
HE_ROUTED64="${HE_ROUTED64:-}"
# Optional extra prefixes to pool from, comma separated (e.g. the tunnel's own
# link /64, which HE routes and which is a DIFFERENT quota bucket from the
# routed /64). Empty keeps the single-prefix behaviour.
HE_EXTRA_PREFIXES="${HE_EXTRA_PREFIXES:-}"
HE_MTU="${HE_MTU:-1480}"
HE_IFACE="he-ipv6"
HE_UPDATE_USER="${HE_UPDATE_USER:-}"
HE_UPDATE_KEY="${HE_UPDATE_KEY:-}"

# --- Proxy defaults, applied only when config.json does not exist yet ------
POOL_SIZE="${POOL_SIZE:-100}"
WEB_USER="${WEB_USER:-admin}"
WEB_PASS="${WEB_PASS:-}"
PROXY_USER="${PROXY_USER:-proxy}"
PROXY_PASS="${PROXY_PASS:-}"
ALLOWED_TARGETS="${ALLOWED_TARGETS:-https://opencode.ai,https://api.kilo.ai,https://oai.endpoints.kepler.ai.cloud.ovh.net,https://cloudflare.com}"
ALLOW_TOKEN="${ALLOW_TOKEN:-}"

REPO="${REPO:-github.com/jeffpecky/ipv6-proxy}"
VERSION="${VERSION:-latest}"
INSTALL_DIR="/opt/ipv6-proxy"
GO_VERSION="1.21.5"
GO_TAR="go${GO_VERSION}.linux-amd64.tar.gz"
GO_URL="https://go.dev/dl/${GO_TAR}"
export PATH=/usr/local/go/bin:$PATH
PURGE_INSTALL=0

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
print_success(){ echo -e "${GREEN}[OK] $1${NC}"; }
print_error(){ echo -e "${RED}[ERROR] $1${NC}"; }
print_warning(){ echo -e "${YELLOW}[WARNING] $1${NC}"; }
print_info(){ echo -e "${BLUE}[INFO] $1${NC}"; }

gen_pass(){
  head -c 24 /dev/urandom | base64 | tr -d '/+=' | head -c 24
}

web_port_open(){
  local port="$1"
  [ -n "$port" ] || return 1
  timeout 3 bash -c ":</dev/tcp/127.0.0.1/$port" >/dev/null 2>&1
}

wait_web_port(){
  local port="$1" max_wait="${2:-180}" waited=0
  while [ $waited -lt $max_wait ]; do
    if web_port_open "$port"; then return 0; fi
    if [ $((waited % 10)) -eq 0 ]; then
      print_info "Waiting for web panel port ${port} to be ready... (${waited}/${max_wait} sec)"
    fi
    sleep 2
    waited=$((waited+2))
  done
  return 1
}

handle_apt_locks(){
  local waited=0
  while fuser /var/lib/dpkg/lock-frontend >/dev/null 2>&1 || fuser /var/lib/dpkg/lock >/dev/null 2>&1 || fuser /var/lib/apt/lists/lock >/dev/null 2>&1; do
    if [ $waited -ge 60 ]; then
      print_warning "Timed out waiting for package manager lock, attempting cleanup"
      killall apt apt-get dpkg unattended-upgr 2>/dev/null || true
      rm -f /var/lib/apt/lists/lock /var/cache/apt/archives/lock /var/lib/dpkg/lock* /var/lib/dpkg/lock-frontend
      dpkg --configure -a 2>/dev/null || true
      return
    fi
    sleep 2; waited=$((waited+2))
  done
}

# --- Hurricane Electric 6in4 tunnel ----------------------------------------
# A VPS with no native IPv6 needs this before the gateway has anything to bind.
# The service is a oneshot that rebuilds the tunnel on every start, so an
# endpoint or prefix change always takes effect.

load_env_file(){
  local f
  for f in "$(dirname "$0")/install.env" /etc/ipv6-proxy.env; do
    if [ -r "$f" ]; then
      # shellcheck disable=SC1090
      . "$f"
      print_info "Loaded settings from $f"
      return 0
    fi
  done
  return 1
}

require_tunnel_settings(){
  local missing=""
  for v in HE_TUNNEL_ID HE_SERVER_V4 HE_SERVER_V6 HE_CLIENT_V6 HE_ROUTED64; do
    eval "val=\${$v}"
    [ -n "$val" ] || missing="$missing $v"
  done
  if [ -n "$missing" ]; then
    print_error "Missing tunnel settings:$missing"
    print_info "Create install.env beside this script (or /etc/ipv6-proxy.env) with:"
    echo "  HE_TUNNEL_ID=123456"
    echo "  HE_SERVER_V4=209.51.161.58"
    echo "  HE_SERVER_V6=2001:470:4:559::1"
    echo "  HE_CLIENT_V6=2001:470:4:559::2"
    echo "  HE_ROUTED64=2001:470:5:559::/64"
    return 1
  fi
  if [ -z "$HE_ENDPOINT_V4" ]; then
    HE_ENDPOINT_V4=$(detect_public_v4) || true
    [ -n "$HE_ENDPOINT_V4" ] || { print_error "Cannot detect the public IPv4; set HE_ENDPOINT_V4"; return 1; }
  fi
  return 0
}

detect_public_v4(){
  local ip=""
  for url in https://ifconfig.me https://api.ipify.org https://ipv4.icanhazip.com; do
    ip=$(curl -4 -s --max-time 8 "$url" 2>/dev/null | tr -d '[:space:]')
    case "$ip" in
      ""|*[!0-9.]*) ip="" ;;
      *) echo "$ip"; return 0 ;;
    esac
  done
  return 1
}

install_tunnel_service(){
  cat >/usr/local/sbin/he-tunnel-up <<TUNNELEOF
#!/bin/bash
# Generated by install.sh for HE tunnel $HE_TUNNEL_ID
# Recreated on every start so endpoint or prefix changes always take effect.
LOCAL_V4="$HE_ENDPOINT_V4"
if [ -f /run/he-endpoint ]; then
  read -r DETECTED_V4 < /run/he-endpoint || true
  [ -n "\$DETECTED_V4" ] && LOCAL_V4="\$DETECTED_V4"
fi
if ip link show $HE_IFACE >/dev/null 2>&1; then
  # Change in place: deleting the link would also delete every pooled /128.
  ip tunnel change $HE_IFACE mode sit remote $HE_SERVER_V4 local "\$LOCAL_V4" ttl 255 || exit 1
else
  ip tunnel add $HE_IFACE mode sit remote $HE_SERVER_V4 local "\$LOCAL_V4" ttl 255 || exit 1
fi
ip link set $HE_IFACE up mtu $HE_MTU
ip -6 addr add $HE_CLIENT_V6/64 dev $HE_IFACE 2>/dev/null || true
ip -6 route replace ::/0 via $HE_SERVER_V6 dev $HE_IFACE metric 1
ip -6 route replace $HE_ROUTED64 dev $HE_IFACE
for p in $(echo "$PREFIX_LIST" | tr ',' ' '); do
  [ -n "$p" ] && ip -6 route replace "$p" dev $HE_IFACE 2>/dev/null || true
done
TUNNELEOF
  cat >/usr/local/sbin/he-tunnel-down <<TUNNELEOF
#!/bin/bash
ip tunnel del $HE_IFACE 2>/dev/null || true
TUNNELEOF
  chmod +x /usr/local/sbin/he-tunnel-up /usr/local/sbin/he-tunnel-down

  if [ -n "$HE_UPDATE_USER" ] && [ -n "$HE_UPDATE_KEY" ]; then
    install_endpoint_updater
  fi

  cat >/etc/systemd/system/he-ipv6.service <<TUNNELEOF
[Unit]
Description=Hurricane Electric 6in4 tunnel ($HE_TUNNEL_ID)
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/he-tunnel-up
ExecStop=/usr/local/sbin/he-tunnel-down

[Install]
WantedBy=multi-user.target
TUNNELEOF
  systemctl daemon-reload
  systemctl enable he-ipv6 >/dev/null 2>&1 || true
  print_success "HE tunnel service installed ($HE_ROUTED64 via $HE_IFACE)"
}

# Keeps the HE endpoint in sync when the public IPv4 changes: writes the
# detected address to /run/he-endpoint, which he-tunnel-up reads on start.
install_endpoint_updater(){
  cat >/usr/local/sbin/he-endpoint-update <<UPDATEEOF
#!/bin/bash
# Generated by install.sh for HE tunnel $HE_TUNNEL_ID
set -u
STATE=/run/he-endpoint
KEYFILE=/etc/he-update.key

current=""
[ -f "\$STATE" ] && current=\$(cat "\$STATE" 2>/dev/null)

detected=""
for url in https://ifconfig.me https://api.ipify.org https://ipv4.icanhazip.com; do
  detected=\$(curl -4 -s --max-time 8 "\$url" 2>/dev/null | tr -d '[:space:]')
  case "\$detected" in ""|*[!0-9.]*) detected="" ;; *) break ;; esac
done

[ -z "\$detected" ] && exit 0
[ "\$detected" = "\$current" ] && exit 0

printf '%s\n' "\$detected" > "\$STATE"

if [ -r "\$KEYFILE" ]; then
  resp=\$(curl -s --max-time 10 -u "\$(cat "\$KEYFILE")" \
    "https://ipv4.tunnelbroker.net/nic/update?hostname=$HE_TUNNEL_ID&myip=\$detected" 2>/dev/null)
  logger -t he-endpoint-update "endpoint \$current -> \$detected: \$resp"
else
  logger -t he-endpoint-update "endpoint \$current -> \$detected (no key, HE not updated)"
fi

/usr/local/sbin/he-tunnel-up
UPDATEEOF
  chmod +x /usr/local/sbin/he-endpoint-update

  ( umask 077; printf '%s:%s\n' "$HE_UPDATE_USER" "$HE_UPDATE_KEY" > /etc/he-update.key )
  chmod 600 /etc/he-update.key

  cat >/etc/systemd/system/he-endpoint-update.service <<UPDATEEOF
[Unit]
Description=Keep the HE tunnel endpoint in sync with the public IPv4
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/he-endpoint-update
UPDATEEOF

  cat >/etc/systemd/system/he-endpoint-update.timer <<UPDATEEOF
[Unit]
Description=Check the HE tunnel endpoint every 5 minutes

[Timer]
OnBootSec=60
OnUnitActiveSec=300

[Install]
WantedBy=timers.target
UPDATEEOF
  systemctl daemon-reload
  systemctl enable he-endpoint-update.timer >/dev/null 2>&1 || true
  print_success "HE endpoint auto-update installed"
}

main(){
  if [ "$(id -u)" -ne 0 ]; then print_error "Root privileges required, please use sudo"; exit 1; fi

  echo "============================================="
  echo "=== Prefixa IPv6 Gateway v7.6 ==="
  echo "============================================="

  load_env_file || true
  require_tunnel_settings || exit 1
  # The link /64 (where HE_CLIENT_V6 lives) is routed to the tunnel endpoint and
  # carries egress on its own. Measured 2026-11-18: the routed /64 answered 429
  # for a model while the link /64 answered 200 in the same minute, so pooling
  # from both gives the rotator a second bucket to fall back to.
  HE_LINK64=""
  if [ -n "$HE_CLIENT_V6" ]; then
    HE_LINK64=$(python3 -c "import ipaddress,sys;print(ipaddress.ip_network(sys.argv[1]+'/64',strict=False))" "$HE_CLIENT_V6" 2>/dev/null || true)
  fi
  PREFIX_LIST="$HE_ROUTED64"
  if [ -n "$HE_LINK64" ] && [ "$HE_LINK64" != "$HE_ROUTED64" ]; then
    PREFIX_LIST="$PREFIX_LIST,$HE_LINK64"
  fi
  if [ -n "$HE_EXTRA_PREFIXES" ]; then
    PREFIX_LIST="$PREFIX_LIST,$HE_EXTRA_PREFIXES"
  fi

  print_info "Tunnel $HE_TUNNEL_ID: $HE_ROUTED64 via $HE_IFACE"
  print_info "Pool prefixes: $PREFIX_LIST"

  if [ -x "$INSTALL_DIR/ipv6-proxy" ] && [ -f /etc/systemd/system/ipv6-proxy.service ]; then
    print_info "IPv6 proxy is already installed, checking web panel"
    systemctl daemon-reload
    systemctl enable ipv6-proxy >/dev/null 2>&1 || true
    PROXY_PORT=$(grep -oP '"port"\s*:\s*"\K[^"]+' "$INSTALL_DIR/config.json" 2>/dev/null || echo 1080)
    WEB_PORT=$(grep -oP '"web_port"\s*:\s*"\K[^"]+' "$INSTALL_DIR/config.json" 2>/dev/null || echo 8080)
    if systemctl is-active --quiet ipv6-proxy; then
      print_info "Service is running"
    else
      print_info "Service is not running, starting it"
      systemctl start ipv6-proxy >/dev/null 2>&1 || true
    fi
    if ! wait_web_port "$WEB_PORT" 60; then
      print_warning "Web panel port ${WEB_PORT} is not responding, trying to restart the service"
      systemctl restart ipv6-proxy >/dev/null 2>&1 || true
      wait_web_port "$WEB_PORT" 120 || true
    fi
    IP=$(curl -s ifconfig.me 2>/dev/null || echo "your-server-IP")
    if web_port_open "$WEB_PORT"; then print_success "Web panel is healthy"; else print_warning "Web panel is still unreachable"; fi
    echo "Current web panel: http://${IP}:${WEB_PORT}"
    echo "Current HTTP proxy: http://proxy:proxy@${IP}:${PROXY_PORT}"
    echo "Current SOCKS5 proxy: socks5://proxy:proxy@${IP}:${PROXY_PORT}"
    if [ -t 0 ]; then
      echo ""
      echo "Choose an action:"
      echo "  1) Skip installation, keep the existing service"
      echo "  2) Update/reinstall, keep the existing config file"
      echo "  3) Uninstall then install, delete old program and config and reconfigure"
      echo "  4) Exit"
      read -r -p "Enter choice (default 1): " INSTALL_CHOICE
      INSTALL_CHOICE=${INSTALL_CHOICE:-1}
    else
      INSTALL_CHOICE=1
    fi
    case "$INSTALL_CHOICE" in
      1) print_success "Installation skipped"; exit 0 ;;
      2) print_warning "Update/reinstall selected, $INSTALL_DIR/config.json will be kept" ;;
      3) print_warning "Uninstall then install selected, $INSTALL_DIR and old config will be deleted"; PURGE_INSTALL=1 ;;
      4) print_info "Exited"; exit 0 ;;
      *) print_warning "Invalid choice, skipping installation by default"; exit 0 ;;
    esac
  fi

  print_info "Cleaning up old service"
  systemctl stop ipv6-proxy.service >/dev/null 2>&1 || true
  systemctl disable ipv6-proxy.service >/dev/null 2>&1 || true
  rm -f /etc/systemd/system/ipv6-proxy.service
  if [ "$PURGE_INSTALL" = "1" ]; then rm -rf "$INSTALL_DIR"; fi
  systemctl daemon-reload

  print_info "Installing dependencies and Go"
  if command -v wget >/dev/null 2>&1 && command -v git >/dev/null 2>&1 && command -v update-ca-certificates >/dev/null 2>&1; then
    print_info "System dependencies already present, skipping apt install"
  else
    handle_apt_locks
    apt-get update >/dev/null 2>&1 || apt-get update --fix-missing >/dev/null 2>&1 || true
    apt-get install -y wget git ca-certificates >/dev/null 2>&1 || { print_error "Failed to install dependencies"; exit 1; }
  fi
  if [ ! -x /usr/local/go/bin/go ] || ! /usr/local/go/bin/go version | grep -q "$GO_VERSION"; then
    rm -rf /usr/local/go
    wget -q "$GO_URL" -O "/tmp/$GO_TAR" || { print_error "Failed to download Go"; exit 1; }
    tar -C /usr/local -xzf "/tmp/$GO_TAR" && rm -f "/tmp/$GO_TAR"
  else
    print_info "Go $GO_VERSION already present, skipping download"
  fi

  # Build from THIS checkout when main.go sits beside the installer. The
  # upstream path does a remote `go install`, which cannot carry local changes
  # (the HE tunnel, the allowlist) — those would silently disappear on
  # reinstall. SRC_DIR is resolved before we cd anywhere.
  SRC_DIR="$(cd "$(dirname "$0")" && pwd)"
  if [ -f "$SRC_DIR/main.go" ] && [ -f "$SRC_DIR/go.mod" ]; then
    LOCAL_BUILD=1
  else
    LOCAL_BUILD=0
  fi

  if [ "$LOCAL_BUILD" = "1" ]; then
    print_info "Building from local source: $SRC_DIR"
  else
    print_info "Building ${REPO}@${VERSION} with go install"
  fi
  mkdir -p "$INSTALL_DIR"
  # A fresh repo may not be indexed by every module proxy yet, so try a few
  # known-good sources (and finally direct VCS) before giving up.
  export GOBIN="$INSTALL_DIR" CGO_ENABLED=0
  BUILD_LOG="/tmp/ipv6-proxy-build.log"
  BUILD_OK=0
  if [ "$LOCAL_BUILD" = "1" ]; then
    if ( cd "$SRC_DIR" && go build -ldflags "-s -w" -o "$INSTALL_DIR/ipv6-proxy" . ) 2>"$BUILD_LOG"; then
      BUILD_OK=1
    else
      print_error "Local build failed: $(tail -n 1 "$BUILD_LOG")"
      exit 1
    fi
  fi
  for proxy in "https://proxy.golang.org,https://goproxy.cn,direct" "https://goproxy.cn,direct" "direct"; do
    [ "$LOCAL_BUILD" = "1" ] && break
    for ref in "$VERSION" main; do
      [ "$BUILD_OK" = "1" ] && break
      print_info "Trying GOPROXY=${proxy} ref=${ref}"
      if GOPROXY="$proxy" go install -ldflags "-s -w" "${REPO}@${ref}" 2>"$BUILD_LOG"; then
        BUILD_OK=1
      else
        print_warning "Build failed: $(tail -n 1 "$BUILD_LOG")"
      fi
    done
    [ "$BUILD_OK" = "1" ] && break
  done
  [ "$BUILD_OK" = "1" ] || { print_error "go install failed, last error: $(tail -n 1 "$BUILD_LOG")"; exit 1; }
  # go names the binary after the last path element of the repo
  BIN_NAME="$(basename "${REPO%%@*}")"
  if [ "$BIN_NAME" != "ipv6-proxy" ] && [ -f "$INSTALL_DIR/$BIN_NAME" ]; then mv -f "$INSTALL_DIR/$BIN_NAME" "$INSTALL_DIR/ipv6-proxy"; fi
  [ -x "$INSTALL_DIR/ipv6-proxy" ] || { print_error "Binary not found after build"; exit 1; }
  print_success "Build complete"

  install_tunnel_service
  systemctl restart he-ipv6 >/dev/null 2>&1 || systemctl start he-ipv6 >/dev/null 2>&1 || true
  if ! ip -6 route show | grep -qF "$HE_ROUTED64"; then
    print_warning "Tunnel is up but $HE_ROUTED64 has no route yet"
  fi

  cat >/etc/systemd/system/ipv6-proxy.service <<SERVICEEOF
[Unit]
Description=Prefixa IPv6 Gateway v7.6
After=network-online.target he-ipv6.service
Wants=network-online.target he-ipv6.service
[Service]
Type=simple
User=root
WorkingDirectory=$INSTALL_DIR
ExecStart=$INSTALL_DIR/ipv6-proxy
CapabilityBoundingSet=CAP_NET_ADMIN CAP_NET_RAW
AmbientCapabilities=CAP_NET_ADMIN CAP_NET_RAW
Restart=always
RestartSec=3
LimitNOFILE=65535
[Install]
WantedBy=multi-user.target
SERVICEEOF
  systemctl daemon-reload

  print_info "Tuning system"
  sysctl -w net.ipv6.neigh.default.gc_thresh1=2048 >/dev/null 2>&1 || true
  sysctl -w net.ipv6.neigh.default.gc_thresh2=4096 >/dev/null 2>&1 || true
  sysctl -w net.ipv6.neigh.default.gc_thresh3=10000 >/dev/null 2>&1 || true
  sysctl -w net.core.somaxconn=8192 >/dev/null 2>&1 || true
  ulimit -n 65535 2>/dev/null || true

  cd "$INSTALL_DIR" || exit 1
  if [ ! -f config.json ]; then
    print_info "Writing config.json for $HE_ROUTED64"
    if [ -z "$WEB_PASS" ]; then WEB_PASS="$(gen_pass)"; fi
    if [ -z "$PROXY_PASS" ]; then PROXY_PASS="$(gen_pass)"; fi
    PREFIX_JSON=$(printf '%s' "$PREFIX_LIST" | tr ',' '\n' | sed 's/^[[:space:]]*//; s/[[:space:]]*$//' | grep -v '^$' | sed 's/.*/"&"/' | paste -sd, -)
    [ -n "$PREFIX_JSON" ] && PREFIX_JSON="[$PREFIX_JSON]" || PREFIX_JSON="[]"
    ALLOW_JSON=$(printf '%s\n' "$ALLOWED_TARGETS" | tr ',' '\n' \
      | sed 's/^[[:space:]]*//; s/[[:space:]]*$//; s|/$||' | grep -v '^$' \
      | sed 's/.*/"&"/' | paste -sd, -)
    [ -n "$ALLOW_JSON" ] && ALLOW_JSON="[$ALLOW_JSON]" || ALLOW_JSON="[]"
    cat > config.json <<CONFIGEOF
{
  "port": "1080",
  "web_port": "8080",
  "web_username": "$WEB_USER",
  "web_password": "$WEB_PASS",
  "username": "$PROXY_USER",
  "password": "$PROXY_PASS",
  "ipv6_prefix": "$HE_ROUTED64",
  "ipv6_prefixes": $PREFIX_JSON,
  "nexthop_addr": "",
  "interface": "$HE_IFACE",
  "initial_pool": $POOL_SIZE,
  "target_pool": $POOL_SIZE,
  "auto_rotate": false,
  "auto_rotate_hours": 6,
  "auto_clean": true,
  "allowed_targets": $ALLOW_JSON,
  "allow_token": "$ALLOW_TOKEN",
  "ports": []
}
CONFIGEOF
    chmod 600 config.json
    print_success "config.json created (pool $POOL_SIZE, $HE_ROUTED64)"
    if [ "$WEB_PASS" = "$PROXY_PASS" ]; then
      print_info "Panel and proxy password: $WEB_PASS (also in $INSTALL_DIR/config.json)"
    else
      print_info "Panel password: $WEB_PASS   Proxy password: $PROXY_PASS"
    fi
    print_info "Allowed targets: ${ALLOWED_TARGETS:-<none: OPEN PROXY>}"
  fi
  PROXY_PORT=$(grep -oP '"port"\s*:\s*"\K[^"]+' config.json 2>/dev/null || echo 1080)
  WEB_PORT=$(grep -oP '"web_port"\s*:\s*"\K[^"]+' config.json 2>/dev/null || echo 8080)
  if command -v ufw >/dev/null 2>&1; then ufw allow "${PROXY_PORT}/tcp" >/dev/null 2>&1 || true; ufw allow "${WEB_PORT}/tcp" >/dev/null 2>&1 || true; fi
  systemctl enable ipv6-proxy >/dev/null 2>&1
  systemctl restart ipv6-proxy
  if systemctl is-active --quiet ipv6-proxy; then
    print_success "Service started successfully"
    if wait_web_port "$WEB_PORT" 180; then
      print_success "Web panel port ${WEB_PORT} is healthy"
    else
      print_warning "Service started, but web panel port ${WEB_PORT} is not responding"
      echo "Check logs: journalctl -u ipv6-proxy -n 80 --no-pager"
      echo "Check listening ports: ss -lntp | grep ${WEB_PORT}"
    fi
  else
    print_warning "Service may have failed to start, check systemctl status ipv6-proxy"
    echo "Check logs: journalctl -u ipv6-proxy -n 80 --no-pager"
  fi
  IP=$(curl -s ifconfig.me 2>/dev/null || echo "your-server-IP")
  echo "Web panel: http://${IP}:${WEB_PORT}"
  echo "HTTP proxy: http://proxy:proxy@${IP}:${PROXY_PORT}"
  echo "SOCKS5 proxy: socks5://proxy:proxy@${IP}:${PROXY_PORT}"
  echo "Config file: $INSTALL_DIR/config.json"
}

# Whole script is parsed before this line runs, so giving main a terminal as stdin
# keeps the interactive prompts working under `curl ... | bash`.
# /dev/tty can exist yet fail to open (a non-interactive ssh session, systemd,
# a pipe). Probe by actually opening it, then fall back to stdin — every prompt
# in this installer is skipped when config.json is generated non-interactively.
if { : </dev/tty; } 2>/dev/null; then main "$@" </dev/tty; else main "$@"; fi
